def graf0(text, font, xpos, ypos, colr=white):
    tr = int(len(font[1]) - 4)  # number of zeros in 'space' glyph sets the tracking (character spacing) in pixels
    for ch in text:  # each character
        glyph = font[font[0].find(ch)]
        w, h = int(glyph[0:2]), int(glyph[2:4])  # the glyph's width and headspace
        glyph = glyph[4:]  # strip prefixes
        n = -(-w//4)  # i.e. ceil(w/4) = number of 4-bit blocks of pixels
        nr = int(len(glyph)/n)  # number of rows
        for y in range(nr):
            row =f'{int(glyph[y*n:(y+1)*n],16):0>{w}b}'  # slice glyph & convert to binary string with leading zeros
            for x in range(w):
                if row[x] == '1': 
                    LCD.pixel(x+xpos, y+ypos+h, colr)
        xpos += w + tr

