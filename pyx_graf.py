def graf0(text, font, xpos, ypos, colr=white):
    tr = int(len(font[1]) - 4)  # number of zeros in 'space' glyph sets the tracking (character spacing) in pixels
    for ch in text:  # each character
        glyph = font[font[0].find(ch)]
        w, h = int(glyph[0:2]), int(glyph[2:4])  # the glyph's width and headspace
        glyph = glyph[4:]  # strip prefixes
        n = -(-w//4)  # i.e. ceil(w/4) = number of 4-bit blocks of pixels
        nr = int(len(glyph)/n)  # number of rows
        for y in range(nr):
            row = f'{int(glyph[y*n:(y+1)*n],16):0>{w}b}'  # slice glyph & convert to binary string with leading zeros
            for x in range(w):
                if row[x] == '1':
                    LCD.pixel(x+xpos, y+ypos+h, colr)
        xpos += w + tr

def graf(text, font, xpos, ypos, overwrite=0, fw=0, colr=None, colr_bk=None):
    if fw:
        fw = int(font[2][0:2])  # glyph width for fixed-width numerals = width of '0'
    if colr is None:  # (if not colr: fails when colr = 0, black)
        try: colr = txt  # 'global' colour setting
        except: colr = white
    if colr_bk is None:
        try: colr_bk = bkg
        except: colr_bk = black
    hh = int(font[1][2:4])  # overall height of overwrite
    if overwrite:
        LCD.fill_rect(xpos, ypos, overwrite, hh, colr_bk) # deletes the line for length = 'overwrite'
    tr = int(len(font[1]) - 4)  # number of zeros in 'space' glyph sets the tracking (character spacing) in pixels
    for ch in text:  # each character
        if ch in 'j':
            xpos -= int(tr/2)  # one day - kerning
        if fw and ch == ':':  # to give time colon rather than punctuation colon, etc.
            xpos +=int(fw/6)
        glyph = font[font[0].find(ch)]
        w, h = int(glyph[0:2]), int(glyph[2:4])  # the glyph's width and headspace
        glyph = glyph[4:]  # strip prefixes (mem.ok)
        n = -(-w//4)  # i.e. ceil(w/4) = number of 4-bit blocks of pixels
        nr = int(len(glyph)/n)  # number of rows
        for y in range(nr):
            row = f'{int(glyph[y*n:(y+1)*n],16):0>{w}b}'  # slice glyph & convert to binary string with leading zeros
            # print(row)
            for x in range(w):
                if row[x] == '1':
                    LCD.pixel(x+xpos, y+ypos+h, colr)
        if ch in 'f':
            xpos -= int(tr/2)
        if fw:       
            if ch in '123456789':
                xpos += fw + tr
                if ch == '1':
                    xpos -= int(fw/6)
            else:
                xpos += w + tr  # f-w only works for nums; use v-w for other characters
            if ch == ':':
                xpos +=int(fw/6)
        else: xpos += w + tr

